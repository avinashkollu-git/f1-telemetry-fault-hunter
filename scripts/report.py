"""Turn results/*.json into reports/REPORT.md plus plots (matplotlib if installed, else ASCII)."""
import argparse
import json
from pathlib import Path

import pandas as pd

try:
    import matplotlib
    matplotlib.use("Agg")  # no display needed
    import matplotlib.pyplot as plt
except ImportError:
    plt = None


def plot_timeline(events, path):
    types = sorted(events.type.unique())
    fig, ax = plt.subplots(figsize=(10, 3.6))
    for i, t in enumerate(types):
        e = events[events.type == t]
        ax.hlines([i] * len(e), e.t_start, e.t_end + 0.5, lw=6)  # +0.5 s so point events are visible
    ax.set_yticks(range(len(types)), types)
    ax.set_xlabel("time in synthetic log (s)")
    ax.set_title("Detected fault events")
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)


def plot_root_cause(grid, rule, path):
    g8 = grid[grid.gear == 8]
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for flag, color, label in [(False, "#bbbbbb", "heartbeat OK"), (True, "#d62728", "heartbeat lost")]:
        d = g8[g8.hb_loss == flag]
        ax.scatter(d.water_temp + (d.rpm % 7 - 3) * 0.04, d.rpm, s=6, c=color, label=label)  # small x-jitter: temp is integer
    for f, op, v in rule:
        if f == "rpm":
            ax.axhline(v, ls="--", c="k", lw=1)
        if f == "water_temp":
            ax.axvline(v, ls="--", c="k", lw=1)
    ax.set_xlabel("coolant temperature (degC, 1 degC resolution)")
    ax.set_ylabel("rpm")
    ax.set_title("Grid points in 8th gear: heartbeat lost vs vehicle state\n(dashed = thresholds the rule search found)")
    ax.legend(loc="lower left")
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)


def ascii_bars(counts):
    top = max(counts.values())
    return "\n".join(f"{k:<14}{'#' * max(1, round(40 * v / top))} {v}" for k, v in counts.items())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="reports")
    ap.add_argument("--real", default="data/real")
    args = ap.parse_args()
    res_dir, out = Path(args.results), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    syn = json.loads((res_dir / "synth_results.json").read_text())
    real = json.loads((res_dir / "real_results.json").read_text())
    events = pd.read_csv(res_dir / "events.csv", dtype={"can_id": str})
    grid = pd.read_csv(res_dir / "hb_grid.csv")
    rc = syn["root_cause"]
    main_rc = rc["state_features"]
    rule = [(s.split()[0], s.split()[1], float(s.split()[2])) for s in main_rc["found_rule"].split(" and ")]

    md = ["# Fault Hunter report", "",
          "Generated by `make report` from `results/`. Synthetic numbers come from the seeded CAN log;",
          "real-data numbers come from public F1 telemetry. Nothing here is about a real car's faults.", ""]

    d, g = syn["decode"], syn["generator"]
    md += ["## Synthetic CAN log", "",
           f"- seed {g['seed']}, {g['laps']} laps, {g['duration_s']} s of driving, {d['frames']} frames, "
           f"{d.get('ERROR_FRAME', 0)} error frames",
           f"- C++ decoder: {d['frames_per_second']} frames/s single-threaded "
           f"({d['seconds']:.3f} s incl. writing CSV)",
           f"- CRC-15: {syn['crc']['matched']}/{syn['crc']['injected_bitflips']} corrupted frames flagged, "
           f"{syn['crc']['false_crc_errors']} false CRC errors", "",
           "| fault type | injected | detected | precision | recall |", "|---|---|---|---|---|"]
    for k, v in syn["detection"].items():
        md.append(f"| {k} | {v['injected']} | {v['detected']} | {v['precision']} | {v['recall']} |")

    md += ["", "### Fault signatures (grouped like regression failures)", "",
           "| signature | events | first (s) | last (s) |", "|---|---|---|---|"]
    md += [f"| {s['signature']} | {s['events']} | {s['first_t']:.2f} | {s['last_t']:.2f} |" for s in syn["signatures"]]

    md += ["", "### Root cause of the intermittent heartbeat loss", "",
           f"- injected (hidden) trigger: `{rc['injected_rule']}`",
           f"- grid points (one per 50 ms heartbeat slot): {rc['grid_points']}, with heartbeat lost: {rc['fault_points']}",
           f"- detected-loss labels vs true trigger: precision {rc['hb_loss_label_vs_true_trigger']['precision']}, "
           f"recall {rc['hb_loss_label_vs_true_trigger']['recall']}", ""]
    for title, s in [("vehicle-state features", main_rc), ("plus slowly trending signals (SoC, battery temp)",
                                                           rc["with_trending_signals"])]:
        rv = s["rule_vs_true_trigger"]
        md += [f"**Search over {title}:** `{s['found_rule']}`, vs true trigger: precision {rv['precision']}, "
               f"recall {rv['recall']}", "", "| step | rule | P | R | F1 |", "|---|---|---|---|---|"]
        md += [f"| {i + 1} | `{h['rule']}` | {h['precision']:.3f} | {h['recall']:.3f} | {h['f1']:.3f} |"
               for i, h in enumerate(s["search_steps"])]
        md += ["", "Runners-up: " + "; ".join(f"`{a['rule']}` (F1 {a['f1']})" for a in s["alternatives"]), ""]

    md += ["## Real F1 telemetry (public feed)", ""]
    if "skipped" in real:
        md.append(f"Skipped: {real['skipped']}")
    else:
        md += [f"Session: {real['session']}. All drivers share identical timestamps: "
               f"{real['all_drivers_share_timestamps']}. Distinct on-track gap instants (> 1 s): "
               f"{real['gap_instants_any_driver']}.", "",
               "| driver | on-track samples | rate (Hz) | dt median / p95 / max (s) | gaps > 1 s | throttle = 104 "
               "| brake values | stuck rpm runs | speed jumps > 300 km/h/s |", "|---|---|---|---|---|---|---|---|---|"]
        for drv, r in real["drivers"].items():
            q = r["dt_on_track_s"]
            md.append(f"| {drv} | {r['on_track_samples']} | {r['rate_hz_on_track']} | {q['median']} / {q['p95']} / "
                      f"{q['max']} | {len(r['gaps_over_1s_on_track'])} | {r['throttle_above_100']} | "
                      f"{r['brake_values']} | {len(r['stuck_rpm_runs'])} | {len(r['speed_change_over_300kmh_per_s'])} |")

    if plt:
        plot_timeline(events, out / "fault_timeline.png")
        plot_root_cause(grid, rule, out / "hb_root_cause.png")
        md += ["", "## Plots", "", "![fault timeline](fault_timeline.png)", "", "![root cause](hb_root_cause.png)"]
        if "skipped" not in real:
            car = pd.read_csv(Path(args.real) / "car_data.csv")
            dt = car[car.Driver == car.Driver.iloc[0]].SessionTime.diff().dropna()
            fig, ax = plt.subplots(figsize=(7, 3.2))
            ax.hist(dt.clip(upper=1.5), bins=60)
            ax.set_yscale("log")
            ax.set_xlabel("interval between samples (s), clipped at 1.5")
            ax.set_title(f"Real feed sample intervals ({car.Driver.iloc[0]}, whole session)")
            fig.tight_layout()
            fig.savefig(out / "real_sample_intervals.png", dpi=110)
            plt.close(fig)
            md += ["", "![real sample intervals](real_sample_intervals.png)"]
    else:
        md += ["", "## Event counts (matplotlib not installed, ASCII)", "", "```",
               ascii_bars(events.type.value_counts().to_dict()), "```"]

    (out / "REPORT.md").write_text("\n".join(md) + "\n")
    print(f"wrote {out / 'REPORT.md'}" + (" and plots" if plt else " (ASCII, no matplotlib)"))


if __name__ == "__main__":
    main()
